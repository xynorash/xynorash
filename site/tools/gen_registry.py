"""Regenerate lib/data/pages_registry.dart from lib/data/pages/**.dart."""
import os

here = os.path.dirname(os.path.abspath(__file__))
data = os.path.join(here, '..', 'lib', 'data')
pages = []
for d, _, fs in os.walk(os.path.join(data, 'pages')):
    for f in fs:
        if f.endswith('.dart'):
            pages.append(os.path.relpath(os.path.join(d, f), data))
pages.sort()
out = ["// GENERATED by tools/gen_registry.py — do not edit.",
       "import '../models/project.dart';"]
out += [f"import '{p}' as p{i};" for i, p in enumerate(pages)]
out += ["", "/// Every project page, in file order. The explorer tree is built from",
        "/// each page's path, so order here only affects ties.",
        "final List<Buffer> kPageBuffers = ["]
out += [f"  p{i}.page," for i in range(len(pages))]
out.append("];")
open(os.path.join(data, 'pages_registry.dart'), 'w').write("\n".join(out) + "\n")
print(len(pages), 'pages registered')
